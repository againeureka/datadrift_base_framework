"""Message catalog for human-readable output (reports, hints, console).

Language is chosen in this order: an explicit ``--lang`` value, the
``DDOC_LANG`` environment variable, then English. Machine-readable
values — verdicts, severity codes, JSON keys — are never translated.
"""
from __future__ import annotations

import os
from typing import Any, Optional

DEFAULT_LANG = "en"
SUPPORTED_LANGS = ("en", "ko")


def resolve_lang(explicit: Optional[str] = None) -> str:
    """Return a supported language code; unknown values fall back to English."""
    raw = explicit or os.environ.get("DDOC_LANG") or DEFAULT_LANG
    code = raw.strip().lower().replace("_", "-").split("-")[0]
    return code if code in SUPPORTED_LANGS else DEFAULT_LANG


