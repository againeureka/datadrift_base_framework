def t(key: str, lang: str = DEFAULT_LANG, **fmt: Any) -> str:
    """Look up ``key`` for ``lang`` (falling back to English) and format it."""
    catalog = MESSAGES.get(lang, MESSAGES[DEFAULT_LANG])
    template = catalog.get(key, MESSAGES[DEFAULT_LANG][key])
    return template.format(**fmt) if fmt else template


def severity_label(code: Optional[str], lang: str) -> str:
    """Display text for a severity code; unknown codes are shown as-is."""
    key = f"severity.{code}"
    return t(key, lang) if key in MESSAGES[DEFAULT_LANG] else str(code)
